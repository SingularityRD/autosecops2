"""scripts/wp/gates.sh: removing a tracked node_modules path is the fix, not a failure.

git:node_modules must fail when a branch adds or modifies a tracked
node_modules path, and must not fire when the branch only deletes one
(``git rm --cached``), which is exactly what its own message asks for.
"""

from __future__ import annotations

import shutil
import subprocess
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[2]
GATES = REPO / "scripts" / "wp" / "gates.sh"

pytestmark = pytest.mark.skipif(shutil.which("git") is None, reason="git not installed")


def _git(cwd: Path, *args: str) -> None:
    subprocess.run(
        ["git", "-c", "user.name=t", "-c", "user.email=t@example.invalid", *args],
        cwd=cwd,
        check=True,
        capture_output=True,
    )


def _repo(tmp_path: Path) -> Path:
    repo = tmp_path / "repo"
    (repo / "scripts" / "wp").mkdir(parents=True)
    shutil.copy2(GATES, repo / "scripts" / "wp" / "gates.sh")
    (repo / "clients" / "web" / "node_modules" / "pkg").mkdir(parents=True)
    (repo / "clients" / "web" / "node_modules" / "pkg" / "index.js").write_text("1\n")
    (repo / "README").write_text("x\n")
    _git(repo, "init", "-q", "-b", "base")
    # info/exclude gets "node_modules" from gates.sh; force-add like a mistake would.
    _git(repo, "add", "-f", ".")
    _git(repo, "commit", "-qm", "base")
    _git(repo, "checkout", "-qb", "work")
    return repo


def _gates(repo: Path) -> str:
    proc = subprocess.run(
        ["bash", "scripts/wp/gates.sh", "--base", "base", "--dry-run"],
        cwd=repo,
        capture_output=True,
        text=True,
        timeout=120,
    )
    return proc.stdout + proc.stderr


def test_deleting_tracked_node_modules_is_not_flagged(tmp_path):
    repo = _repo(tmp_path)
    _git(repo, "rm", "-rq", "--cached", "clients/web/node_modules")
    _git(repo, "commit", "-qm", "untrack node_modules")

    out = _gates(repo)
    assert "RESULT: PASS (nothing changed)" in out, out
    assert "PLAN  git:node_modules: bash" not in out, out


def test_modifying_tracked_node_modules_is_flagged(tmp_path):
    repo = _repo(tmp_path)
    (repo / "clients" / "web" / "node_modules" / "pkg" / "index.js").write_text("2\n")
    _git(repo, "commit", "-qam", "touch node_modules")

    out = _gates(repo)
    assert "PLAN  git:node_modules: bash" in out, out
