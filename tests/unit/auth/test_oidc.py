def test_a_rotated_key_triggers_one_jwks_refetch(provider):
    oidc.clear_caches()
    rotating = MockIdP()
    try:
        with respx.mock(assert_all_called=False) as mock:
            rotating.install(mock)

            async def run():
                discovery = await oidc.get_discovery(provider)
                await oidc._get_jwks(discovery)  # warm the cache with rsa-1
                rotating.rsa_kid = "rsa-2"  # provider rotates
                # The throttle would otherwise hold the refetch back.
                oidc._jwks_cache[discovery.jwks_uri].fetched_at -= 120
                token = rotating.sign(rotating.claims_for(NONCE))
                return await oidc.validate_id_token(
                    token, provider=provider, discovery=discovery, nonce=NONCE
                )

            claims = asyncio.run(run())
        assert claims["sub"] == "subject-alice"
        assert rotating.jwks_fetches == 2
    finally:
        oidc.clear_caches()


