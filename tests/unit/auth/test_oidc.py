@pytest.fixture
def keys(idp):
    return oidc._parse_jwks(idp.jwks())


def _validate(token, provider, discovery, keys, nonce=NONCE):
    return validate_id_token_with_keys(
        token, provider=provider, discovery=discovery, keys=keys, nonce=nonce
    )


def _code_of(token, provider, discovery, keys, nonce=NONCE) -> str:
    with pytest.raises(OidcError) as info:
        _validate(token, provider, discovery, keys, nonce)
    return info.value.code


# --- signature --------------------------------------------------------------


def test_a_valid_rs256_token_passes(idp, provider, discovery, keys):
    claims = _validate(idp.sign(idp.claims_for(NONCE)), provider, discovery, keys)
    assert claims["sub"] == "subject-alice"
    assert claims["email"] == "alice@example.com"


def test_a_valid_es256_token_passes(idp, provider, discovery, keys):
    token = idp.sign(idp.claims_for(NONCE), alg="ES256")
    assert _validate(token, provider, discovery, keys)["sub"] == "subject-alice"


def test_a_token_signed_by_another_key_is_refused(idp, provider, discovery, keys):
    impostor = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    token = idp.sign(idp.claims_for(NONCE), key=impostor)  # claims the real kid
    assert _code_of(token, provider, discovery, keys) == "signature"


def test_a_tampered_payload_is_refused(idp, provider, discovery, keys):
    header, payload, signature = idp.sign(idp.claims_for(NONCE)).split(".")
    forged = idp.sign(idp.claims_for(NONCE, sub="subject-mallory")).split(".")[1]
    token = ".".join([header, forged, signature])
    assert payload != forged
    assert _code_of(token, provider, discovery, keys) == "signature"


def test_alg_none_is_refused(idp, provider, discovery, keys):
    token = jwt.encode(idp.claims_for(NONCE), None, algorithm="none")
    assert _code_of(token, provider, discovery, keys) == "signature"


def test_hmac_with_the_public_key_as_secret_is_refused(idp, provider, discovery, keys):
    """Key confusion: HS256 'signed' with the provider's public key."""
    public_pem = idp.rsa_key.public_key().public_bytes(
        serialization.Encoding.PEM, serialization.PublicFormat.SubjectPublicKeyInfo
    )
    token = _hs256(idp.claims_for(NONCE), public_pem, idp.rsa_kid)
    assert _code_of(token, provider, discovery, keys) == "signature"


def _hs256(claims, secret: bytes, kid: str) -> str:
    # PyJWT refuses PEM-looking HMAC secrets, so build the token by hand.
    import base64
    import hashlib
    import hmac
    import json

    def b64(raw: bytes) -> str:
        return base64.urlsafe_b64encode(raw).rstrip(b"=").decode()

    head = b64(json.dumps({"alg": "HS256", "typ": "JWT", "kid": kid}).encode())
    body = b64(json.dumps(claims).encode())
    sig = hmac.new(secret, f"{head}.{body}".encode(), hashlib.sha256).digest()
    return f"{head}.{body}.{b64(sig)}"


def test_an_unknown_kid_is_refused(idp, provider, discovery, keys):
    token = idp.sign(idp.claims_for(NONCE), kid="not-a-key")
    assert _code_of(token, provider, discovery, keys) == "signature"


def test_an_rsa_kid_cannot_carry_an_es256_token(idp, provider, discovery, keys):
    token = idp.sign(idp.claims_for(NONCE), alg="ES256", kid=idp.rsa_kid)
    assert _code_of(token, provider, discovery, keys) == "signature"


