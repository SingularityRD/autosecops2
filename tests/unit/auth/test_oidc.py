def test_discovery_must_name_the_configured_issuer(idp, provider):
    oidc.clear_caches()
    idp.discovery_overrides = {"issuer": "https://evil.test/realms/soc"}
    try:
        with respx.mock(assert_all_called=False) as mock:
            idp.install(mock)
            with pytest.raises(OidcError) as info:
                asyncio.run(oidc.get_discovery(provider))
        assert info.value.code == "provider"
    finally:
        idp.discovery_overrides = {}
        oidc.clear_caches()


