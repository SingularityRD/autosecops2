def test_wrong_audience_is_refused(idp, provider, discovery, keys):
    token = idp.sign(idp.claims_for(NONCE, aud="some-other-client"))
    assert _code_of(token, provider, discovery, keys) == "claims"


def test_wrong_issuer_is_refused(idp, provider, discovery, keys):
    token = idp.sign(idp.claims_for(NONCE, iss="https://evil.test/realms/soc"))
    assert _code_of(token, provider, discovery, keys) == "claims"


def test_several_audiences_need_azp_naming_us(idp, provider, discovery, keys):
    no_azp = idp.sign(idp.claims_for(NONCE, aud=[CLIENT_ID, "other"]))
    assert _code_of(no_azp, provider, discovery, keys) == "claims"
    wrong_azp = idp.sign(idp.claims_for(NONCE, aud=[CLIENT_ID, "other"], azp="other"))
    assert _code_of(wrong_azp, provider, discovery, keys) == "claims"
    good = idp.sign(idp.claims_for(NONCE, aud=[CLIENT_ID, "other"], azp=CLIENT_ID))
    assert _validate(good, provider, discovery, keys)["azp"] == CLIENT_ID


def test_an_expired_token_is_refused(idp, provider, discovery, keys):
    now = int(time.time())
    token = idp.sign(idp.claims_for(NONCE, iat=now - 400, exp=now - 120))
    assert _code_of(token, provider, discovery, keys) == "expired"


def test_expiry_within_the_skew_is_tolerated_but_not_beyond(
    idp, provider, discovery, keys
):
    now = int(time.time())
    inside = idp.sign(idp.claims_for(NONCE, iat=now - 100, exp=now - 30))
    assert _validate(inside, provider, discovery, keys)
    strict = provider.model_copy(update={"clock_skew_seconds": 0})
    assert _code_of(inside, strict, discovery, keys) == "expired"


def test_a_token_issued_in_the_future_is_refused(idp, provider, discovery, keys):
    now = int(time.time())
    token = idp.sign(idp.claims_for(NONCE, iat=now + 600, exp=now + 900))
    assert _code_of(token, provider, discovery, keys) == "claims"


def test_a_token_issued_long_ago_is_refused_even_if_unexpired(
    idp, provider, discovery, keys
):
    now = int(time.time())
    token = idp.sign(idp.claims_for(NONCE, iat=now - 3600, exp=now + 3600))
    assert _code_of(token, provider, discovery, keys) == "expired"


def test_missing_required_claims_are_refused(idp, provider, discovery, keys):
    for missing in ("exp", "iat", "sub"):
        token = idp.sign(idp.claims_for(NONCE, **{missing: None}))
        assert _code_of(token, provider, discovery, keys) == "claims", missing


def test_a_nonce_mismatch_is_refused(idp, provider, discovery, keys):
    token = idp.sign(idp.claims_for("another-login"))
    assert _code_of(token, provider, discovery, keys) == "nonce"
    no_nonce = idp.sign(idp.claims_for(None))
    assert _code_of(no_nonce, provider, discovery, keys) == "nonce"


