# --- role mapping -----------------------------------------------------------


def test_no_matching_group_means_viewer(provider):
    assert map_role(provider, {"groups": ["nobody"]}, ROLES) == "role-viewer"


def test_first_matching_mapping_wins(provider):
    mapped = provider.model_copy(
        update={
            "role_mappings": [
                RoleMapping(value="soc-seniors", role_id="role-senior-analyst"),
                RoleMapping(value="soc", role_id="role-analyst"),
            ]
        }
    )
    assert map_role(mapped, {"groups": ["soc", "soc-seniors"]}, ROLES) == (
        "role-senior-analyst"
    )
    assert map_role(mapped, {"groups": "soc"}, ROLES) == "role-analyst"


def test_a_mapping_can_use_any_claim(provider):
    mapped = provider.model_copy(
        update={
            "role_mappings": [
                RoleMapping(claim="roles", value="SOC.Manager", role_id="role-manager")
            ]
        }
    )
    assert map_role(mapped, {"roles": ["SOC.Manager"]}, ROLES) == "role-manager"
    assert map_role(mapped, {"groups": ["SOC.Manager"]}, ROLES) == "role-viewer"


def test_admin_is_reached_only_through_an_allowed_explicit_mapping(provider):
    to_admin = provider.model_copy(
        update={
            "role_mappings": [RoleMapping(value="soc-admins", role_id="role-admin")]
        }
    )
    # A stored config that bypassed validation still cannot grant Admin.
    assert map_role(to_admin, {"groups": ["soc-admins"]}, ROLES) == "role-viewer"
    allowed = to_admin.model_copy(update={"allow_admin_mapping": True})
    assert map_role(allowed, {"groups": ["soc-admins"]}, ROLES) == "role-admin"
    assert map_role(allowed, {"groups": ["soc"]}, ROLES) == "role-viewer"


def test_a_stored_admin_default_falls_back_to_viewer(provider):
    tampered = provider.model_copy(update={"default_role_id": "role-admin"})
    assert map_role(tampered, {}, ROLES) == "role-viewer"


def test_pkce_challenge_is_s256_of_the_verifier():
    # RFC 7636 appendix B.
    verifier = "dBjftJeZ4CVP-mB92K27uhbUJU1p1r_wW1gFWFOEjXk"
    assert (
        oidc.code_challenge(verifier) == "E9Melhoa2OwvFrEMTJguCHaoeK1t8URWbuGJSstw-cM"
    )
    assert 43 <= len(oidc.new_code_verifier()) <= 128
